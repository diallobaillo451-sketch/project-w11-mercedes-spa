// Cockpit + volant vivant + panneau de réglages + drapeau : captures iPhone 844×390 (et 1080p)
import { chromium } from '@playwright/test'
const [url = 'http://127.0.0.1:4199/', pre = 'ck', W = '844', H = '390', dpr = '3'] = process.argv.slice(2)
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const ctx = await b.newContext({ viewport: { width: +W, height: +H }, deviceScaleFactor: +dpr, isMobile: true, hasTouch: true, userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1' })
const p = await ctx.newPage(); const errs = []
p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()) })
await p.goto(url); await p.waitForFunction(() => window.__w11 && !document.getElementById('bootGo')?.hidden, null, { timeout: 300000 })
await p.click('#bootGo'); await p.waitForTimeout(1000)
await p.click('[data-act=timetrial]'); await p.waitForTimeout(500)
await p.evaluate(() => { const w = window.__w11; w.setCam('cockpit') })
// gaz pendant 4 s (rapport, vitesse, LEDs)
await p.evaluate(() => { const w = window.__w11; w.input.st.throttle = 1 })
const pt = await p.locator('#pThrottle').boundingBox(); await p.touchscreen.tap(pt.x + 20, pt.y + 20)
await p.waitForTimeout(6000)
await p.screenshot({ path: `/workspace/w11/out/shots/${pre}_cockpit_conduite.png` })
await p.click('#bWheel'); await p.waitForTimeout(300)
const tap = async sel => { const bb = await p.locator(sel).first().boundingBox(); await p.touchscreen.tap(bb.x + bb.width / 2, bb.y + bb.height / 2); await p.waitForTimeout(150) }
await tap('[data-w="bb+"]'); await tap('[data-w="pit"]'); await tap('[data-w="din-"]')
const st1 = await p.evaluate(() => { const c = window.__w11.game.car; return { bb: c.setup.brakeBias, pit: c.pitLim, diffOff: c.setup.diffOff, kmh: c.forwardSpeed() * 3.6 } })
await p.evaluate(() => window.__w11.game.session.setFlag('yellow', 30)); await p.waitForTimeout(1500)
await p.screenshot({ path: `/workspace/w11/out/shots/${pre}_cockpit_volant_drapeau.png` })
await tap('[data-w="page"]'); await p.waitForTimeout(1200)
await p.screenshot({ path: `/workspace/w11/out/shots/${pre}_cockpit_page_pneus.png` })
await p.evaluate(() => { window.__w11.game.session.setFlag('red', 30); window.__w11.setCam('free'); const c = window.__w11.ren.cams; c.orbitYaw = 0; c.orbitPitch = 0.35; c.orbitDist = 3.5 })
await p.waitForTimeout(1500)
await p.screenshot({ path: `/workspace/w11/out/shots/${pre}_volant_ext.png` })
console.log(JSON.stringify({ st1, errs: errs.slice(0, 6) }))
await b.close()
