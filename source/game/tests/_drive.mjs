import { chromium } from '@playwright/test'
const W = Number(process.argv[2] || 844), H = Number(process.argv[3] || 390)
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const ctx = await b.newContext({ viewport: { width: W, height: H }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 })
const p = await ctx.newPage()
p.on('pageerror', e => console.log('PAGEERR', String(e)))
p.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()) })
await p.goto('http://127.0.0.1:5199/?q=medium')
await p.waitForSelector('#bootGo:not([hidden])', { timeout: 240000 })
await p.screenshot({ path: '/tmp/d_boot.png' })
await p.click('#bootGo'); await p.waitForTimeout(800)
await p.screenshot({ path: '/tmp/d_menu.png' })
await p.click('[data-act=timetrial]'); await p.waitForTimeout(500)
// pédale d'accélérateur tenue par pointer events (doigt en haut = 100 %)
const r = await p.locator('#pThrottle').boundingBox()
await p.mouse.move(r.x + r.width / 2, r.y + 10); await p.mouse.down()
await p.waitForTimeout(3000)
await p.screenshot({ path: '/tmp/d_drive.png' })
console.log(await p.evaluate(() => { const g = window.__w11.game; return JSON.stringify({ thr: g.ctl.throttle, v: (g.car.speed * 3.6).toFixed(0), gear: g.car.gear, s: g.car.s.toFixed(0), lap: g.session.timing.lapStart }) }))
await p.mouse.up()
await b.close()
